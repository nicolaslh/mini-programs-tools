import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const rootDir = resolve(fileURLToPath(new URL('..', import.meta.url)))
const sourceDir = join(rootDir, 'src')
const toolsDir = join(sourceDir, 'tools')
const generatedNotice = '// Generated by scripts/generate-tools.mjs. Do not edit manually.\n'

const toolDirectories = readdirSync(toolsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort()

const seenIds = new Set()
const seenRoutes = new Set()

const manifests = toolDirectories.map((directory) => {
  const manifestPath = join(toolsDir, directory, 'manifest.json')
  if (!existsSync(manifestPath)) {
    throw new Error(`Missing manifest: ${relative(rootDir, manifestPath)}`)
  }

  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
  const requiredFields = ['id', 'name', 'description', 'category', 'route', 'icon', 'keywords']

  for (const field of requiredFields) {
    if (manifest[field] === undefined || manifest[field] === '') {
      throw new Error(`${relative(rootDir, manifestPath)} is missing \"${field}\"`)
    }
  }

  if (!/^[a-z][a-z0-9-]*$/.test(manifest.id)) {
    throw new Error(`${manifest.id} is not a valid tool id`)
  }
  if (manifest.id !== directory) {
    throw new Error(`Tool id \"${manifest.id}\" must match directory \"${directory}\"`)
  }
  if (!Array.isArray(manifest.keywords)) {
    throw new Error(`${manifest.id}.keywords must be an array`)
  }
  if (seenIds.has(manifest.id)) {
    throw new Error(`Duplicate tool id: ${manifest.id}`)
  }
  if (seenRoutes.has(manifest.route)) {
    throw new Error(`Duplicate tool route: ${manifest.route}`)
  }

  const expectedRoute = `/tools/${directory}/index`
  if (manifest.route !== expectedRoute) {
    throw new Error(`${manifest.id}.route must be \"${expectedRoute}\"`)
  }
  if (!existsSync(join(toolsDir, directory, 'index.vue'))) {
    throw new Error(`Missing page component for ${manifest.id}`)
  }

  seenIds.add(manifest.id)
  seenRoutes.add(manifest.route)
  return { directory, manifest }
})

manifests.sort((left, right) => {
  const orderDifference = (left.manifest.order ?? 999) - (right.manifest.order ?? 999)
  return orderDifference || left.manifest.name.localeCompare(right.manifest.name, 'zh-CN')
})

const imports = manifests
  .map(({ directory }, index) => `import tool${index} from './${directory}/manifest.json'`)
  .join('\n')
const items = manifests.map((_, index) => `  tool${index} as ToolManifest,`).join('\n')
const generatedRegistry = `${generatedNotice}import type { ToolManifest } from '@/types/tool'\n${imports}\n\nexport const tools: ToolManifest[] = [\n${items}\n]\n\nexport function getToolById(id: string) {\n  return tools.find((tool) => tool.id === id)\n}\n`

const pages = {
  pages: [
    {
      path: 'pages/index/index',
      style: {
        navigationBarTitleText: '工具集',
      },
    },
    {
      path: 'pages/social/index',
      style: {
        navigationBarTitleText: '社交界面',
      },
    },
  ],
  subPackages: [
    {
      root: 'tools',
      pages: manifests.map(({ directory, manifest }) => ({
        path: `${directory}/index`,
        style: {
          navigationBarTitleText: manifest.name,
        },
      })),
    },
  ],
  globalStyle: {
    navigationBarTextStyle: 'black',
    navigationBarTitleText: '工具集',
    navigationBarBackgroundColor: '#ffffff',
    backgroundColor: '#f4f6f8',
  },
}

writeFileSync(join(toolsDir, 'generated.ts'), generatedRegistry)
writeFileSync(join(sourceDir, 'pages.json'), `${JSON.stringify(pages, null, 2)}\n`)

console.log(`Generated registry and routes for ${manifests.length} tools.`)
